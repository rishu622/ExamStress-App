// Helper to generate 30-day biomarker trajectory
const generate30DayBiomarkers = (type: 'healthy' | 'stressed' | 'declining_red' | 'improving') => {
  const points = [];
  const now = new Date();
  
  for (let i = 29; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const dateStr = d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    const dayNum = 30 - i;
    
    if (type === 'healthy') {
      points.push({
        day: dayNum,
        date: dateStr,
        pitchVariability: Math.round(45 + Math.sin(i * 0.5) * 8 + Math.random() * 4),
        speechRate: Math.round(145 + Math.random() * 10 - 5),
        responseLatency: Math.round(180 + Math.random() * 30),
        energyLevel: parseFloat((0.82 + Math.random() * 0.1 - 0.05).toFixed(2)),
        absolutistWords: Math.floor(Math.random() * 2),
      });
    } else if (type === 'stressed') {
      points.push({
        day: dayNum,
        date: dateStr,
        pitchVariability: Math.round(32 - (i > 15 ? (30 - i) * 0.5 : 0) + Math.random() * 3),
        speechRate: Math.round(160 + (i > 15 ? (30 - i) * 1.2 : 0) + Math.random() * 6),
        responseLatency: Math.round(290 + (i > 15 ? (30 - i) * 10 : 0) + Math.random() * 40),
        energyLevel: parseFloat((0.62 - (i > 15 ? (30 - i) * 0.015 : 0)).toFixed(2)),
        absolutistWords: Math.floor(2 + Math.random() * 3),
      });
    } else if (type === 'declining_red') {
      // Significant drop starting from day 14
      const progress = i <= 15 ? (15 - i) / 15 : 0;
      points.push({
        day: dayNum,
        date: dateStr,
        pitchVariability: Math.round(48 - progress * 32 + Math.random() * 4),
        speechRate: Math.round(140 - progress * 45 + Math.random() * 8),
        responseLatency: Math.round(190 + progress * 660 + Math.random() * 50),
        energyLevel: parseFloat((0.85 - progress * 0.57).toFixed(2)),
        absolutistWords: Math.round(1 + progress * 11),
      });
    } else { // improving
      const progress = (30 - i) / 30;
      points.push({
        day: dayNum,
        date: dateStr,
        pitchVariability: Math.round(25 + progress * 20 + Math.random() * 5),
        speechRate: Math.round(110 + progress * 30 + Math.random() * 5),
        responseLatency: Math.round(650 - progress * 400 + Math.random() * 30),
        energyLevel: parseFloat((0.35 + progress * 0.45).toFixed(2)),
        absolutistWords: Math.round(8 - progress * 6),
      });
    }
  }
  return points;
};

